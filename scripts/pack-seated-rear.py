"""Export the centered rear seated pose on the existing fixed world canvas."""
from pathlib import Path
from PIL import Image,ImageDraw
import json,hashlib
root=Path(__file__).resolve().parent.parent
geometry={};audit=[]
board=Image.new('RGBA',(768,512),(239,231,213,255))
for i,skin in enumerate(['man','woman','granny']):
 source=root/'artwork/seating-direction'/f'{skin}.png'
 im=Image.open(source).convert('RGBA')
 if im.width!=im.height:raise ValueError(f'Review non-square source before normalization: {skin} {im.size}')
 scale=.22*1280/im.width
 pivot=(628*im.width/1280,1157*im.height/1280)
 frame=Image.new('RGBA',(384,512));resized=im.resize((round(im.width*scale),round(im.height*scale)),Image.Resampling.LANCZOS)
 offset=(round(192-pivot[0]*scale),round(468-pivot[1]*scale));frame.alpha_composite(resized,offset)
 bounds=frame.getchannel('A').point(lambda p:255 if p>24 else 0).getbbox()
 assert bounds and bounds[0]>0 and bounds[1]>0 and bounds[2]<384 and bounds[3]<512,(skin,bounds)
 board.alpha_composite(frame.resize((256,341),Image.Resampling.LANCZOS),(i*256,85))
 if skin!='man':frame=frame.resize((192,256),Image.Resampling.LANCZOS)
 output=root/'public/assets/seating-direction'/f'{skin}.webp';frame.save(output,quality=91,method=4)
 final_bounds=frame.getchannel('A').point(lambda p:255 if p>24 else 0).getbbox()
 geometry[skin]={'image':f'assets/seating-direction/{skin}.webp','top':final_bounds[1]}
 audit.append({'skin':skin,'source':source.relative_to(root).as_posix(),'sourceDimensions':im.size,'scale':scale,'sourcePivot':pivot,'canvas':frame.size,'groundPivot':[192,468] if skin=='man' else[96,234],'bounds':final_bounds,'bytes':output.stat().st_size,'sha256':hashlib.sha256(output.read_bytes()).hexdigest()})
(root/'src/room/seatedRearGeometry.ts').write_text('// Generated by scripts/pack-seated-rear.py. Centered rear-view poses.\nexport const SEATED_REAR_POSES = '+json.dumps(geometry,separators=(',',':'))+';\n',encoding='utf-8')
board.convert('RGB').save(root/'docs/seating-direction/poses.jpg',quality=95)
(root/'docs/seating-direction/assets.json').write_text(json.dumps(audit,indent=2)+'\n',encoding='utf-8')
print(json.dumps(audit))
