"""Pack reviewed generated poses into a fixed world canvas. No per-frame auto-crop/recentering.
Manual source pivots/scale preserve head size; alpha bounds are inspection only.
Prop crops are export bounds for separate static objects, not actor animation pivots.
"""
from pathlib import Path
from PIL import Image,ImageDraw
import json,hashlib
ROOT=Path(__file__).resolve().parent.parent
SOURCE=ROOT/'artwork/visual-v2'
OUT=ROOT/'public/assets/visual-v2'
OUT.mkdir(parents=True,exist_ok=True)
W,H=384,512
PIVOT=(192,468)
# file, uniform scale, manually measured ground anchor, hand grip (source pixels)
poses=[
 ('reference',.33,(605,1204),None),('front',.33,(585,1235),None),
 ('crouch',.23,(790,1170),None),('kneel',.23,(740,1155),None),
 ('seated',.23,(650,1110),None),('kneel',.23,(740,1155),None),
 ('bow-mid',.23,(710,1135),None),('bow-low',.25,(650,1050),None),('bow-floor',.25,(630,1050),None),
 ('offer-chest',.33,(610,1204),(728,292)),('offer-raise',.27,(500,1460),(622,226)),
 ('offer-reach',.27,(470,1500),(800,530)),('offer-place',.27,(450,1490),(872,520)),
 ('offer-release',.27,(450,1490),(910,615))]
frames=[];geometry={};audit=[]
def add(im,name,scale,pivot,hand=None):
 cell=Image.new('RGBA',(W,H))
 resized=im.resize((round(im.width*scale),round(im.height*scale)),Image.Resampling.LANCZOS)
 xy=(round(PIVOT[0]-pivot[0]*scale),round(PIVOT[1]-pivot[1]*scale))
 # Bounds are checked before compositing so truncation cannot silently pass.
 bounds=resized.getchannel('A').point(lambda p:255 if p>24 else 0).getbbox()
 target=(bounds[0]+xy[0],bounds[1]+xy[1],bounds[2]+xy[0],bounds[3]+xy[1])
 if not (0<=target[0]<target[2]<=W and 0<=target[1]<target[3]<=H):raise ValueError(f'Clipped pose {name}: {target}')
 cell.alpha_composite(resized,xy)
 index=len(frames);frames.append(cell)
 entry={'top':target[1]}
 if hand:entry['hand']={'x':round(PIVOT[0]+(hand[0]-pivot[0])*scale),'y':round(PIVOT[1]+(hand[1]-pivot[1])*scale)}
 geometry[index]=entry;audit.append({'cell':index,'source':name,'scale':scale,'sourcePivot':pivot,'sourceHand':hand,'bounds':target})
for name,scale,pivot,hand in poses:add(Image.open(SOURCE/'characters/lam'/f'{name}.png').convert('RGBA'),name,scale,pivot,hand)
for filename in ['walk-rear','walk-front-alpha']:
 im=Image.open(SOURCE/'characters/lam'/f'{filename}.png').convert('RGBA')
 if im.getchannel('A').getextrema()[0]!=0:raise ValueError(f'{filename} is not transparent')
 for i in range(8):
  col,row=i%4,i//4
  crop=im.crop((round(col*im.width/4),round(row*im.height/2),round((col+1)*im.width/4),round((row+1)*im.height/2)))
  # fixed grid and pivot; no alpha-bounds centering or independent body-height scaling
  add(crop,f'{filename}:{i}',.92,(235,430 if row==0 else 434))
atlas=Image.new('RGBA',(W*6,H*5))
for i,im in enumerate(frames):atlas.alpha_composite(im,((i%6)*W,(i//6)*H))
atlas.save(SOURCE/'lam-atlas.png')
atlas.save(OUT/'lam-atlas.webp',quality=90,method=4,exact=False)
preview=frames[4];preview=preview.crop(preview.getchannel('A').getbbox());preview.thumbnail((192,220));preview.save(OUT/'lam-preview.webp',quality=90,method=4)
(ROOT/'src/room/visualGeometry.ts').write_text('// Generated by scripts/pack-visual-assets.py from manually reviewed source pivots.\nexport const LAM_GEOMETRY: Record<number,{top:number;hand?:{x:number;y:number}}> = '+json.dumps(geometry,separators=(',',':'))+';\n',encoding='utf-8')
for file in (SOURCE/'props').glob('*.png'):
 im=Image.open(file).convert('RGBA');alpha=im.getchannel('A')
 if alpha.getextrema()[0]!=0:raise ValueError(f'{file.name} lacks transparency')
 bounds=alpha.point(lambda p:255 if p>8 else 0).getbbox();im=im.crop(bounds);im.thumbnail((384,384),Image.Resampling.LANCZOS)
 im.save(OUT/(file.stem+'.webp'),quality=90,method=4,exact=False)
for layout,size in [('desktop',(1920,1080)),('mobile',(1080,1920))]:
 im=Image.open(SOURCE/'scene'/f'hall-{layout}.png').convert('RGB');im.thumbnail(size,Image.Resampling.LANCZOS);im.save(OUT/f'hall-{layout}.webp',quality=87,method=4)
for name,color in [('light',(245,240,226,255)),('dark',(30,23,17,255))]:
 board=Image.new('RGBA',(6*192,5*256),color);draw=ImageDraw.Draw(board)
 for i,im in enumerate(frames):
  thumb=im.resize((192,256),Image.Resampling.LANCZOS);x,y=(i%6)*192,(i//6)*256;board.alpha_composite(thumb,(x,y));draw.line((x+76,y+234,x+116,y+234),fill=(171,133,84));draw.text((x+5,y+5),str(i),fill=(150,125,95))
 board.convert('RGB').save(ROOT/'docs/visual-upgrade'/f'poses-{name}.jpg',quality=93)
# Loop studies are for frame QA; browser sequence capture is a separate deliverable.
for name,ids,ms in [('walk-rear',list(range(14,22)),100),('walk-front',list(range(22,30)),100),('bow',[5,6,7,8,8,7,6,5],180)]:
 loop=[]
 for index in ids:
  bg=Image.new('RGBA',(W,H),(48,35,24,255));bg.alpha_composite(frames[index]);loop.append(bg)
 loop[0].save(ROOT/'docs/visual-upgrade'/f'{name}-loop.webp',save_all=True,append_images=loop[1:],duration=ms,loop=0,quality=90)
(ROOT/'docs/visual-upgrade'/'frame-normalization.json').write_text(json.dumps({'canvas':[W,H],'groundPivot':PIVOT,'frames':audit},indent=2)+'\n',encoding='utf-8')
print(json.dumps({'frames':len(frames),'atlasBytes':(OUT/'lam-atlas.webp').stat().st_size,'webAssets':[{'file':p.name,'bytes':p.stat().st_size} for p in OUT.iterdir()]},indent=2))
