"""Compile separately reviewed native-canvas hand annotations for legacy ritual art.

This does not infer anatomy, scale another appearance's contacts, or modify any image.
The source atlas hash and opaque samples protect against accidentally using stale contacts.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'artwork/animation-v3/ritual-contacts'
OUTPUT = ROOT / 'src/room/ritualContactGeometry.ts'
CELLS = set(range(9, 14))


def main():
    annotations = json.loads((SOURCE / 'annotations.json').read_text(encoding='utf-8'))
    compiled = {}
    review = []
    board = Image.new('RGB', (5 * 320, 3 * 300), '#e8e2d7')
    draw = ImageDraw.Draw(board)
    for row, (appearance, record) in enumerate(annotations['appearances'].items()):
        path = ROOT / 'public' / record['atlas']
        sha = hashlib.sha256(path.read_bytes()).hexdigest()
        if sha != record['sha256']:
            raise ValueError(f'Atlas changed after contact review: {appearance}')
        atlas = Image.open(path).convert('RGBA')
        width, height = record['canvasWidth'], record['canvasHeight']
        if atlas.size != (width * 6, height * 5):
            raise ValueError(f'Atlas grid changed: {appearance}')
        if set(map(int, record['frames'])) != CELLS:
            raise ValueError(f'Missing ritual contact cells: {appearance}')
        frames = {}
        for col, (cell_id, source) in enumerate(record['frames'].items()):
            cell_id = int(cell_id)
            cell = atlas.crop((cell_id % 6 * width, cell_id // 6 * height,
                               cell_id % 6 * width + width, cell_id // 6 * height + height))
            alpha = cell.getchannel('A')

            def point(values):
                if len(values) != 2 or not all(isinstance(v, (int, float)) for v in values):
                    raise ValueError(f'Invalid point: {appearance}/{cell_id}')
                x, y = values
                if not (0 < x < width and 0 < y < height):
                    raise ValueError(f'Contact outside native canvas: {appearance}/{cell_id}')
                return {'x': x, 'y': y}

            frame = {field: point(source[field]) for field in ('hand', 'leftHand', 'rightHand')}
            if len(source['handMask']) < 3:
                raise ValueError(f'Missing foreground contour: {appearance}/{cell_id}')
            frame['handMask'] = [point(p) for p in source['handMask']]
            frame['gripType'] = source['gripType']
            frame['activeHands'] = source['activeHands']
            samples = {}
            for field in ('hand', 'leftHand', 'rightHand'):
                x, y = round(frame[field]['x']), round(frame[field]['y'])
                nearby = alpha.crop((max(0, x-2), max(0, y-2), min(width, x+3), min(height, y+3)))
                samples[field] = nearby.getextrema()[1]
                if samples[field] < 100:
                    raise ValueError(f'Contact misses artwork: {appearance}/{cell_id}/{field}')
            frames[cell_id] = frame
            review.append({'appearance': appearance, 'cell': cell_id, 'opaqueSamples': samples})

            # A fixed native crop, enlarged for review only. Markers do not alter runtime images.
            crop_box = (width * 176 / 384, height * 96 / 512,
                        width * 336 / 384, height * 272 / 512)
            tile = cell.crop(crop_box).resize((300, 260), Image.Resampling.NEAREST)
            tile_bg = Image.new('RGBA', tile.size, '#e8e2d7')
            tile_bg.alpha_composite(tile)
            origin = (col * 320, row * 300 + 24)
            board.paste(tile_bg.convert('RGB'), origin)
            draw.text((origin[0]+4, row*300+4), f'{appearance} cell {cell_id}', fill='#403020')
            def preview_point(p):
                return (origin[0] + (p['x']-crop_box[0])/(crop_box[2]-crop_box[0])*300,
                        origin[1] + (p['y']-crop_box[1])/(crop_box[3]-crop_box[1])*260)
            draw.line([preview_point(p) for p in frame['handMask']] + [preview_point(frame['handMask'][0])],
                      fill='#bf793c', width=2)
            for field, color in [('hand', '#138870'), ('leftHand', '#aa4992'), ('rightHand', '#376bb0')]:
                x, y = preview_point(frame[field])
                draw.ellipse((x-3, y-3, x+3, y+3), outline=color, width=2)
        compiled[appearance] = {key: record[key] for key in ('atlas', 'sha256', 'canvasWidth', 'canvasHeight')}
        compiled[appearance]['frames'] = frames
    source = "// Generated by scripts/pack-ritual-contacts.py from separately reviewed native-canvas annotations.\n"
    source += "import type { Appearance } from './protocol.ts';\n"
    source += "import type { RitualContactAtlas } from './ritualContactTypes.ts';\n"
    source += 'export const RITUAL_CONTACT_GEOMETRY:Record<Appearance,RitualContactAtlas> = '
    source += json.dumps(compiled, ensure_ascii=False, separators=(',', ':')) + ';\n'
    OUTPUT.write_text(source, encoding='utf-8')
    board.save(SOURCE / 'review.png')
    (SOURCE / 'review.json').write_text(json.dumps({'method': annotations['method'], 'frames': review}, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({'appearances': len(compiled), 'frames': len(review)}))


if __name__ == '__main__':
    main()
