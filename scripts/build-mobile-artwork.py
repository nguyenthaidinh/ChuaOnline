"""Build half-resolution atlases without changing frame grids or logical geometry."""
from pathlib import Path
import hashlib
import json
import re
from PIL import Image

root = Path(__file__).resolve().parent.parent
paths = set()
for geometry in (root / 'src/room').glob('*Geometry.ts'):
    paths.update(re.findall(r"assets/[^'\"`\s]+\.webp", geometry.read_text(encoding='utf-8')))
paths = sorted(p for p in paths if 'animation-v3/' in p or p.endswith('-atlas.webp'))
output = root / 'public/assets/mobile'
output.mkdir(parents=True, exist_ok=True)
records = {}
for path in paths:
    source = root / 'public' / path
    with Image.open(source) as original:
        assert original.width % 2 == original.height % 2 == 0
        resized = original.resize((original.width // 2, original.height // 2), Image.Resampling.LANCZOS)
        temp = output / 'atlas.tmp.webp'
        resized.save(temp, 'WEBP', quality=88, method=6)
        digest = hashlib.sha256(temp.read_bytes()).hexdigest()
        target = output / (source.stem + '-' + digest[:12] + '.webp')
        temp.replace(target)
        records[path] = dict(image=target.relative_to(root / 'public').as_posix(),
            width=resized.width, height=resized.height, sourceWidth=original.width, sourceHeight=original.height,
            sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(), sha256=digest,
            bytes=target.stat().st_size)
(root / 'src/room/mobileArtworkManifest.ts').write_text(
    '// Generated by scripts/build-mobile-artwork.py; preserve logical atlas geometry.\n'
    + 'export const MOBILE_ARTWORK = ' + json.dumps(records, indent=2) + ' as const;\n', encoding='utf-8')
print(json.dumps(dict(atlases=len(records), bytes=sum(r['bytes'] for r in records.values()),
    rgbaMiB=sum(r['width']*r['height']*4 for r in records.values())/1048576)))
