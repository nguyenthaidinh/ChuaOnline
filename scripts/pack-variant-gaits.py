"""Compile eight actual walking directions and matching neutral poses per identity."""
import json
from animation_bank import ROOT, compile_bank, read_selection

SOURCE = ROOT/'artwork/animation-v3/variant-gaits-v1'
HEADINGS = ('rear', 'rearRight', 'right', 'frontRight', 'front', 'frontLeft', 'left', 'rearLeft')
PHASES = ('00-contact', '01-loading', '02-passing', '03-swing', '04-opposite-contact',
          '05-opposite-loading', '06-opposite-passing', '07-opposite-swing')
IDS = [heading+'/'+phase for heading in HEADINGS for phase in PHASES] + [heading+'/stand' for heading in HEADINGS]


def main():
    for appearance in ('woman', 'granny'):
        read_selection(SOURCE/appearance, IDS)
    output = {}
    for appearance in ('woman', 'granny'):
        asset, frames = compile_bank(SOURCE/appearance, IDS, appearance+'-gaits')
        geometry = {frame['id']:{'cell':frame['cell'], 'id':frame['id'].replace('/', '-'), 'top':frame['bounds'][1]}
                    for frame in frames}
        output[appearance] = {'asset':asset,
            'walks':{heading:[geometry[heading+'/'+phase] for phase in PHASES] for heading in HEADINGS},
            'stands':{heading:geometry[heading+'/stand'] for heading in HEADINGS}}
    declaration = '''// Generated by pack-variant-gaits.py; logical canvas384x512, webLOD144x192.
import type { Heading8 } from './locomotion.ts';
type Glyph={cell:number;id:string;top:number};
interface GaitBank {asset:{image:string;sha256:string;width:number;height:number;columns:number;rows:number;cellWidth:number;cellHeight:number};walks:Record<Heading8,readonly Glyph[]>;stands:Record<Heading8,Glyph>}
export const VARIANT_GAITS:Record<'woman'|'granny',GaitBank> = '''
    (ROOT/'src/room/variantGaitGeometry.ts').write_text(declaration+json.dumps(output)+';\n', encoding='utf-8')
    print(json.dumps({key:value['asset'] for key,value in output.items()}))


if __name__ == '__main__':
    main()
