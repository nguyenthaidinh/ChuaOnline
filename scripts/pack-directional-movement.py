"""Export separately authored left/right walk poses without mirroring or alpha recentering."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw
from pose_canvas import CANVAS, GROUND_PIVOT, normalize_pose

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'artwork/animation-v3/directions-v1'
PUBLIC = ROOT / 'public/assets/animation-v3'
PHASES = ['00-contact', '01-loading', '02-passing', '03-swing',
          '04-opposite-contact', '05-opposite-loading', '06-opposite-passing', '07-opposite-swing']


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    selection_path = SOURCE / 'selection.json'
    selection = json.loads(selection_path.read_text(encoding='utf-8')) if selection_path.exists() else {}
    def source_path(direction, phase):
        return SOURCE / selection.get(f'{direction}/{phase}', f'{direction}/{phase}.png')
    missing = [f'{direction}/{phase}.png' for direction in ('left', 'right') for phase in PHASES
               if not source_path(direction, phase).is_file()]
    if missing:
        raise SystemExit('Missing directional poses: ' + ', '.join(missing))
    PUBLIC.mkdir(parents=True, exist_ok=True)
    atlas = Image.new('RGBA', (CANVAS[0] * 4, CANVAS[1] * 4))
    boards = {name: Image.new('RGBA', (192 * 4, 276 * 4), color)
              for name, color in [('light', '#e8e2d7'), ('dark', '#20170f')]}
    pens = {name: ImageDraw.Draw(board) for name, board in boards.items()}
    geometry = {}
    frames = []
    for direction in ('left', 'right'):
        geometry[direction] = []
        sequence = []
        for phase in PHASES:
            path = source_path(direction, phase)
            image, audit = normalize_pose(path)
            cell = len(frames)
            x, y = cell % 4, cell // 4
            atlas.alpha_composite(image, (x * CANVAS[0], y * CANVAS[1]))
            frame_id = f'{direction}-{phase}'
            record = {'cell': cell, 'id': frame_id, 'source': path.relative_to(ROOT).as_posix(), **audit}
            frames.append(record)
            geometry[direction].append({'cell': cell, 'id': frame_id, 'top': audit['bounds'][1]})
            for name, board in boards.items():
                board.alpha_composite(image.resize((192, 256), Image.Resampling.LANCZOS), (x * 192, y * 276 + 20))
                pens[name].text((x * 192 + 6, y * 276 + 4), frame_id,
                                fill='#765936' if name == 'light' else '#dbc29a')
            background = Image.new('RGBA', CANVAS, '#302318')
            background.alpha_composite(image)
            sequence.append(background)
        sequence[0].save(SOURCE / f'{direction}-loop.webp', save_all=True, append_images=sequence[1:],
                         duration=120, loop=0, quality=92, method=4)
    master = SOURCE / 'directional-atlas.webp'
    atlas.save(master, quality=93, method=4)
    for name, board in boards.items():
        board.convert('RGB').save(SOURCE / f'contact-sheet-{name}.jpg', quality=95)
    texture = atlas.resize((768, 1024), Image.Resampling.LANCZOS)
    temporary = PUBLIC / 'directional-walk-packing.webp'
    texture.save(temporary, quality=93, method=4)
    sha = digest(temporary)
    destination = PUBLIC / f'directional-walk-{sha[:12]}.webp'
    temporary.replace(destination)
    artwork = {'image': destination.relative_to(ROOT / 'public').as_posix(), 'sha256': sha,
               'width': 768, 'height': 1024, 'columns': 4, 'rows': 4,
               'cellWidth': 192, 'cellHeight': 256}
    review = {'status': 'compiled', 'appearance': 'man', 'canvas': list(CANVAS),
              'groundPivot': list(GROUND_PIVOT), 'master': master.name, 'masterSha256': digest(master),
              'directions': ['left', 'right'], 'mirrored': False, 'frames': frames, 'production': artwork,
              'loopMs': 960, 'loopNote': 'Atlas-source preview, not a browser video or FPS measurement.'}
    (SOURCE / 'review.json').write_text(json.dumps(review, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    generated = '// Generated by scripts/pack-directional-movement.py; geometry uses logical 384x512 units.\n'
    generated += 'export const DIRECTIONAL_ARTWORK = ' + json.dumps(artwork) + ' as const;\n'
    generated += "export const DIRECTIONAL_WALKS:Record<'left'|'right',readonly {cell:number;id:string;top:number}[]> = "
    generated += json.dumps(geometry) + ';\n'
    (ROOT / 'src/room/directionalMovementGeometry.ts').write_text(generated, encoding='utf-8')
    print(json.dumps({'frames': len(frames), 'production': artwork, 'bytes': destination.stat().st_size}))


if __name__ == '__main__':
    main()
