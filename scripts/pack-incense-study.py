"""Pack authored incense poses, measured hand geometry and small production textures."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw
from pose_canvas import CANVAS, GROUND_PIVOT, normalize_pose

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / 'artwork/animation-v3/incense-v1'
PUBLIC = ROOT / 'public/assets/animation-v3'
IDS = ['00-neutral','01-reach','02-grasp','03-chest','04-lift','05-forehead',
       '06-bow-start','07-bow-hold','08-bow-return','09-lower','10-extend','11-near-burner',
       '12-contact-closed','13-release','14-open','15-withdraw','16-return','17-palms','18-rest',
       '19-pickup-lift','20-mid-lift','21-prayer-lower','22-arms-lower']


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def production_texture(image, name, columns, rows):
    # Geometry stays in logical 384x512 units. Only the immutable texture uses 192x256 cells.
    texture = image.resize((image.width // 2, image.height // 2), Image.Resampling.LANCZOS)
    temporary = PUBLIC / f'{name}-packing.webp'
    texture.save(temporary, quality=93, method=4)
    sha = digest(temporary)
    output = PUBLIC / f'{name}-{sha[:12]}.webp'
    temporary.replace(output)
    return {'image': output.relative_to(ROOT / 'public').as_posix(), 'sha256': sha,
            'width': texture.width, 'height': texture.height,
            'columns': columns, 'rows': rows, 'cellWidth': 192, 'cellHeight': 256}


def main():
    annotations = json.loads((DIRECTORY / 'annotations.json').read_text(encoding='utf-8'))
    source_names = annotations.get('sourceOverrides',{})
    missing = [name for name in IDS[1:] if not (DIRECTORY / source_names.get(name,f'{name}.png')).is_file()]
    if missing:
        raise SystemExit('Missing incense poses: ' + ', '.join(missing))
    PUBLIC.mkdir(parents=True, exist_ok=True)
    rows = (len(IDS)+3)//4
    atlas = Image.new('RGBA', (CANVAS[0] * 4, CANVAS[1] * rows))
    board = Image.new('RGBA', (192 * 4, 276 * rows), (233,226,210,255))
    draw = ImageDraw.Draw(board)
    frames, geometry = [], []
    for index, name in enumerate(IDS):
        source = ROOT / 'artwork/animation-v3/transitions-v1/00-stand-angled.png' if index == 0 else DIRECTORY / source_names.get(name,f'{name}.png')
        image, audit = normalize_pose(source)
        data = annotations['frames'].get(name, {})
        holds = 2 <= index <= 12 or name in ('19-pickup-lift','20-mid-lift')
        if holds and any(field not in data for field in ('grip','leftHand','rightHand','handMask')):
            raise SystemExit(f'Missing measured hand geometry: {name}')
        scale = audit['scale']
        offset = [round(GROUND_PIVOT[i] - audit['sourcePivot'][i] * scale) for i in range(2)]

        def point(value):
            if len(value) != 2 or not all(isinstance(v,(int,float)) for v in value):
                raise ValueError(f'Invalid point: {name}')
            result = [round(value[i] * scale + offset[i], 3) for i in range(2)]
            if not (0 <= result[0] <= CANVAS[0] and 0 <= result[1] <= CANVAS[1]):
                raise ValueError(f'Contact outside canvas: {name}')
            return dict(zip(('x','y'),result))

        shape = {'id':name, 'top':audit['bounds'][1], 'holdsIncense':holds}
        for field in ('grip','leftHand','rightHand'):
            if field in data:
                shape[field] = point(data[field])
        if 'handMask' in data:
            if len(data['handMask']) < 3:
                raise ValueError(f'Hand mask needs a polygon: {name}')
            shape['handMask'] = [point(value) for value in data['handMask']]
        x, y = index % 4, index // 4
        atlas.alpha_composite(image, (x * CANVAS[0], y * CANVAS[1]))
        board.alpha_composite(image.resize((192,256), Image.Resampling.LANCZOS),(x*192,y*276+20))
        draw.text((x*192+6,y*276+4),name,fill=(80,65,40))
        frames.append({'id':name,'phase':data.get('phase',name),'source':source.relative_to(ROOT).as_posix(),**audit,**shape})
        geometry.append(shape)
    output = DIRECTORY / 'incense-atlas.webp'
    atlas.save(output, quality=93, method=4)
    board.convert('RGB').save(DIRECTORY / 'contact-sheet.jpg',quality=95)
    incense_asset = production_texture(atlas,'incense',4,rows)
    review = {'status':'compiled','qaReport':'docs/animation-v3/incense-v1/README.md',
              'image':output.name,'imageHash':digest(output),
              'width':384,'height':512,'columns':4,'rows':rows,'durationMs':5000,
              'groundPivot':list(GROUND_PIVOT),'frames':frames,'production':incense_asset}
    (DIRECTORY / 'review.json').write_text(json.dumps(review,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    generated = "// Generated by scripts/pack-incense-study.py; hand coordinates are logical atlas units.\n"
    generated += "import type { IncenseGeometry } from './modernArtworkTypes.ts';\n"
    generated += 'export const INCENSE_ARTWORK = '+json.dumps(incense_asset)+' as const;\n'
    generated += 'export const INCENSE_PROP = '+json.dumps(annotations['prop'])+' as const;\n'
    generated += 'export const INCENSE_GEOMETRY:readonly IncenseGeometry[] = '+json.dumps(geometry,ensure_ascii=False)+';\n'
    (ROOT / 'src/room/incenseGeometry.ts').write_text(generated,encoding='utf-8')

    study = ROOT / 'artwork/animation-v3/transitions-v2'
    transition = json.loads((study / 'review.json').read_text(encoding='utf-8'))
    sequences = json.loads((study / 'sequences.json').read_text(encoding='utf-8'))['clips']
    with Image.open(study / transition['image']) as image:
        transition_asset = production_texture(image.convert('RGBA'),'transitions',4,6)
    walk_root = ROOT / 'artwork/animation-v3/walk-v1'
    walk = json.loads((walk_root / 'review.json').read_text(encoding='utf-8'))
    with Image.open(walk_root / walk['image']) as image:
        walk_asset = production_texture(image.convert('RGBA'),'walk-rear',4,3)
    clips = {}
    for clip in ('standUp','sitDown'):
        clips[clip] = [{ 'id':step['frameId'],'index':step['index'],'startMs':step['startMs'],'endMs':step['endMs'],
                         'rootOffset':step['rootOffset'],'top':transition['frames'][step['index']]['bounds'][1] }
                        for step in sequences[clip]['steps']]
    generated = "// Generated from reviewed transition/walk studies; no dev modules are imported at runtime.\n"
    generated += "import type { MovementGeometry } from './modernArtworkTypes.ts';\n"
    generated += 'export const MOVEMENT_ARTWORK = '+json.dumps(transition_asset)+' as const;\n'
    generated += 'export const WALK_ARTWORK = '+json.dumps(walk_asset)+' as const;\n'
    generated += 'export const MOVEMENT_CLIPS:Record<\'standUp\'|\'sitDown\',readonly MovementGeometry[]> = '+json.dumps(clips)+';\n'
    idle_index = next(i for i,f in enumerate(transition['frames']) if f['id']=='10-seated-rear')
    generated += 'export const MODERN_IDLE = '+json.dumps({'id':'10-seated-rear','index':idle_index,'top':transition['frames'][idle_index]['bounds'][1]})+' as const;\n'
    generated += 'export const WALK_GEOMETRY = '+json.dumps([{'id':f['id'],'top':f['bounds'][1]} for f in walk['frames']])+' as const;\n'
    (ROOT / 'src/room/modernMovementGeometry.ts').write_text(generated,encoding='utf-8')
    print(json.dumps({'frames':len(frames),'production':[incense_asset,transition_asset,walk_asset]}))


if __name__ == '__main__':
    main()
